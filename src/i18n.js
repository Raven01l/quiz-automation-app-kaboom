export const DICTS = { tr, en };
export const LANGS = ['tr', 'en'];

export function translate(lang, key, vars) {
  let text = DICTS[lang]?.[key] ?? DICTS.tr[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) text = text.split(`{${k}}`).join(String(v));
  return text;
}

// A question's text in the chosen language. Imported questions may use plain strings.
export function localize(q, lang) {
  const pick = (v) => (v && typeof v === 'object' && !Array.isArray(v) ? v[lang] ?? v.tr ?? v.en : v);
  return { question: pick(q.question) || '', answers: pick(q.answers) || [], fact: pick(q.fact) || '' };
}
